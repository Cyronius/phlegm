"""Generate gelu_lut.h: the tanh-GELU as 256 linear pieces over [-8, 8) for aie::linear_approx.

    python open_kernels/designs/trit_embed/gelu_lut.py          # rewrites gelu_lut.h
    python open_kernels/designs/trit_embed/gelu_lut.py --check  # fails if gelu_lut.h is stale

fused2.h's gelu_bf reads it. Piece i covers [-8 + i/16, -8 + (i + 1)/16). Its slope is bf16 and its
offset fp32, as the bf16 linear_approx requires. Of the seven bf16 slopes nearest the chord, it keeps the
one with the smallest worst-case error, with the offset that is minimax over every bf16 input in the
piece. The core rounds its fp32 input to bf16 first and clamps the index, so the first piece is exactly
0 (GELU(x) < 1e-14 there) and the last exactly x. It prints the worst error against the fp64 GELU of
the bf16 input.
"""
import argparse
import sys
from pathlib import Path

import numpy as np
from ml_dtypes import bfloat16

HERE = Path(__file__).resolve().parent
PIECES, LO, STEP = 256, -8.0, 1 / 16


def gelu(x):
    return 0.5 * x * (1 + np.tanh(np.sqrt(2 / np.pi) * (x + 0.044715 * x ** 3)))


with np.errstate(invalid="ignore"):
    BF16 = (np.arange(1 << 16, dtype=np.uint32) << 16).view(np.float32).astype(np.float64)
BF16 = np.unique(BF16[np.isfinite(BF16)])


def bf16_grid(a, b):
    """Every bf16 value in [a, b)."""
    return BF16[(BF16 >= a) & (BF16 < b)]


def pieces():
    slopes, offsets, worst = [], [], 0.0
    for i in range(PIECES):
        a = LO + i * STEP
        x = bf16_grid(a, a + STEP)
        y = gelu(x)
        if i == 0:
            s, o = 0.0, 0.0
        elif i == PIECES - 1:
            s, o = 1.0, 0.0
        else:
            chord = float(bfloat16((gelu(a + STEP) - gelu(a)) / STEP))
            best = None
            for k in range(-3, 4):
                bits = int(np.float32(chord).view(np.uint32)) + (k << 16)
                if not 0 <= bits < 1 << 32:
                    continue
                s = float(np.array([bits], np.uint32).view(np.float32)[0])
                r = y - s * x
                o = float(np.float32((r.max() + r.min()) / 2))
                e = np.abs(r - o).max()
                if best is None or e < best[0]:
                    best = (e, s, o)
            _, s, o = best
        assert np.float32(s).view(np.uint32) & 0xFFFF == 0
        worst = max(worst, float(np.abs(y - (s * x + o)).max()))
        slopes.append(s)
        offsets.append(o)
    return slopes, offsets, worst


def header(slopes, offsets):
    """linear_approx layout: (slope, offset) pairs, four pieces per 128-bit row, each row twice."""
    vals = []
    for g in range(0, PIECES, 4):
        row = [v for i in range(g, g + 4) for v in (slopes[i], offsets[i])]
        vals += row + row
    body = ',\n'.join('  ' + ', '.join(f'{v!r}f' if v != int(v) else f'{v:.1f}f' for v in vals[j:j + 8])
                      for j in range(0, len(vals), 8))
    return (f'#pragma once\n// Generated by gelu_lut.py: tanh-GELU, {PIECES} linear pieces over [{LO:g}, {-LO:g}), '
            f'for aie::linear_approx<bfloat16, aie::lut<4, float, bfloat16>>\n'
            f'// (index bias {PIECES // 2}, step bits -4). Do not edit.\n'
            f'static constexpr unsigned kGeluPieces = {PIECES};\n'
            f'#define GELU_LUT_BODY {{ \\\n{body.replace(chr(10), " \\" + chr(10))} }}\n'
            f'__attribute__((weak)) alignas(aie::vector_decl_align) float gelu_lut_ab[{len(vals)}] = GELU_LUT_BODY;\n'
            f'__attribute__((weak)) alignas(aie::vector_decl_align) float gelu_lut_cd[{len(vals)}] = GELU_LUT_BODY;\n')


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    slopes, offsets, worst = pieces()
    text = header(slopes, offsets)
    print(f'worst |error| against fp64 GELU of the bf16 input: {worst:.3g}')
    path = HERE / 'gelu_lut.h'
    if a.check:
        if path.read_text() != text:
            sys.exit('gelu_lut.h is stale: run gelu_lut.py')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
